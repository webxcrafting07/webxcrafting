async function expandBlog() {
  await mongoose.connect(MONGODB_URI as string)
  
  const targetSlug = "ecommerce-web-design-trends-2026"
  const blog = await Blog.findOne({ slug: targetSlug })
  
  if (blog) {
    blog.content = massiveContent
    blog.readTime = 14 
    await blog.save()
    console.log("Successfully expanded Blog 5 to 2000+ words!")
  } else {
    console.log("Could not find the blog in the database.")
  }
  
  process.exit(0)
}

